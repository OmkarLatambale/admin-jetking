import axios from "axios";

const API_URL_ANALYTICS = `${import.meta.env.VITE_API_URL}interviews/analytics`;
const API_URL_TABLE = `${import.meta.env.VITE_API_URL}interviews/interview-table-data`;

export const fetchAnalytics = async () => {
  try {
    const token = localStorage.getItem("accessToken");
    const response = await axios.get(API_URL_ANALYTICS, {
      headers: { Authorization: `Bearer ${token}` },
    });
    return { status: "success", data: response.data };
  } catch (error) {
    const message =
      error.response?.data?.message || "Failed to fetch analytics data";
    return { status: "error", data: message };
  }
};

export const fetchInterviewTableData = async (url = null) => {
  try {
    const token = localStorage.getItem("accessToken");
    const requestUrl = url || API_URL_TABLE;
    
    const response = await axios.get(requestUrl, {
      headers: { Authorization: `Bearer ${token}` },
    });
    
    return { status: "success", data: response.data };
  } catch (error) {
    const message =
      error.response?.data?.message || "Failed to fetch interview table data";
    return { status: "error", data: message };
  }
};

// Download Excel generated by backend
export const downloadInterviewExcel = async () => {
  try {
    const token = localStorage.getItem("accessToken");
    const url = `${import.meta.env.VITE_API_URL}interviews/download/Excel`;

    const resp = await axios.get(url, {
      headers: { Authorization: `Bearer ${token}` },
      responseType: "blob", 
    });

    // Try to read filename from Content-Disposition, else fallback
    const cd = resp.headers["content-disposition"] || resp.headers["Content-Disposition"];
    let filename = "interview_data.xlsx";
    if (cd) {
      const match = /filename\*=UTF-8''([^;]+)|filename="?([^"]+)"?/i.exec(cd);
      const extracted = decodeURIComponent(match?.[1] || match?.[2] || "");
      if (extracted) filename = extracted;
    }

    return { status: "success", data: { blob: resp.data, filename } };
  } catch (error) {
    const message =
      error.response?.data?.message ||
      error.message ||
      "Failed to download Excel";
    return { status: "error", data: message };
  }
};
